-- 출처: F팀 `backend-mqtt-guide` (2026-08-05) §6 "랙 슬롯"
--
--   | 랙 | 접근점 x | 도킹 x | 적재점 x | y (12칸)                                    |
--   | A  | 5.0      | 2.60   | 0.95     | 9.3 10.5 11.8 13.2 14.5 15.8 17.2 18.5      |
--   | B  | 14.5     | 11.95  | 10.20    | 19.7 21.2 22.5 23.8                         |
--   선반 높이(포크 목표) 13.25 · 진입 yaw 3.1416(서쪽)
--
-- 기존 테스트 슬롯(SLOT-01/02)은 지우지 않는다. 필요하면 아래 5장 참고.
--
-- =============================================================================
-- 1. 단위 — 전부 m 로 본다 (2026-08-07 팀 결정)
-- =============================================================================
-- 시뮬 좌표(20 × 30 격자)를 그대로 미터로 간주한다. 즉 격자 1칸 = 1 m 이고,
-- 이 테이블의 모든 길이 컬럼은 같은 단위를 쓴다 — 변환하지 않는다.
--
--   destination_x / destination_y   m   ← MQTT 계약값 그대로. 백엔드는 변환하지 않는다
--   fork_height                     m   ← 그대로 task.dropoff 로 나감
--   usable_height / usable_width    m   ← 카메라가 잰 화물 치수와 직접 비교
--
-- 이전에는 "시뮬 단위 vs 실물 m 이 섞여 있다"고 보고 경고를 달아 두었으나, 팀 합의로
-- 시뮬 좌표를 m 로 확정했다. 따라서 변환 코드는 넣지 않는다.
--
-- ⚠️ 다만 fork_height 13.25 는 F팀 문서가 준 값 그대로다. 이 가정대로면 "포크를 13.25 m
--    까지 올린다"는 뜻이 되어 아래 usable_height 2.00 m 와 바로 이어지지 않는다
--    (한 칸 높이 2 m 인데 들어올림 목표가 13 m). fork_height 는 task 페이로드로 그대로
--    나가는 계약값이라 여기서 임의로 바꾸지 않았다 — F팀 확인이 필요하다.
--
-- =============================================================================
-- 2. usable_height 2.00 m — F팀 문서에 없어 팀이 정한 값
-- =============================================================================
-- 문서가 준 것은 좌표와 포크 목표 높이뿐이고, "한 칸에 얼마나 높은 화물이 들어가는가"는
-- 없다. 그런데 컬럼이 NOT NULL 이고 CHECK(usable_height > 0) 이라 비워 둘 수 없다.
--
-- 2026-08-07 결정: **2.00 m** (직전 값 1.00 m 는 너무 낮아 대부분의 화물이 거부됐다).
-- 이 값으로 통과하는 화물 높이는 다음과 같다.
--
--     usable_height 2.00 ≥ 화물높이 + 팔레트 0.12 + 여유 0.25
--     → 화물높이 ≤ 1.63 m 까지 적재 가능
--
-- 실측값이 아니라 합의값이다. 실측이 나오면 갱신할 것:
--     UPDATE storage_slot SET usable_height = <실측 m> WHERE slot_code = 'A001';
--
-- usable_width 는 NULL 로 둔다 — NULL 은 "폭 제약을 모른다"는 뜻이고 폭 검사를 건너뛴다.
-- 0 으로 채우면 모든 화물이 탈락하므로 절대 쓰지 말 것(PlacementService 주석 참고).
--
-- =============================================================================
-- 3. 깊이(depth)는 재지 않기로 했다 — 컬럼도 두지 않는다
-- =============================================================================
-- 스테이션 카메라가 정면 하나뿐이라 ai/src/station/pipeline.py 가 depth_cm 을 항상 null
-- 로 낸다(규격 v1.0 명시). 측정할 수 없는 값을 슬롯 쪽에만 넣어 두면 "검사하는 것처럼"
-- 보이므로 storage_slot 에도 깊이 컬럼을 두지 않는다.
--
-- 같은 이유로 화물 회전(가로↔세로 교환) 판정도 하지 않는다 — 두 축을 모두 알아야 성립한다.
--
-- =============================================================================
-- 4. destination_x 에 "접근점"을 넣는 이유
-- =============================================================================
-- F팀 문서: "접근점까지만 Nav2 로 가고, 그 뒤 도킹·적재·후진은 차량이 자체 수행한다.
--            백엔드는 접근점 도착을 확인한 뒤 place_rack 만 보내면 된다."
-- 따라서 도킹 x(2.60/11.95)·적재점 x(0.95/10.20)는 차량 몫이라 DB 에 넣지 않는다.
-- 넣어 두면 백엔드가 그리로 보내야 하는 것처럼 오해를 부른다.
--
-- destination_heading 은 degree 다(스키마 주석 기준). 문서의 yaw 3.1416 rad = 180.0 도.
-- =============================================================================

-- 5. 기존 테스트 슬롯을 지우고 싶다면 이 두 줄의 주석을 풀 것.
