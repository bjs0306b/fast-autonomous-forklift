-- =============================================================================
-- 출처: F팀 `backend-mqtt-guide` (2026-08-05) §6 "랙 슬롯"
--
--   | 랙 | 접근점 x | 도킹 x | 적재점 x | y (12칸)                                    |
--   | A  | 5.0      | 2.60   | 0.95     | 9.3 10.5 11.8 13.2 14.5 15.8 17.2 18.5      |
--   | B  | 14.5     | 11.95  | 10.20    | 19.7 21.2 22.5 23.8                         |
--   선반 높이(포크 목표) 13.25 · 진입 yaw 3.1416(서쪽)
--
-- 기존 테스트 슬롯(SLOT-01/02)은 지우지 않는다. 필요하면 아래 4장 참고.
--
-- =============================================================================
-- ⚠️ 1. 이 테이블은 단위가 섞여 있다 — 반드시 읽을 것
-- =============================================================================
-- 같은 행 안에서 컬럼마다 단위가 다르다. 스키마 주석은 전부 "(m)"이라고 적혀 있지만
-- 실제로는 아래와 같이 쓰인다.
--
--   destination_x / destination_y   시뮬 좌표 (0~20 × 0~30)   ← MQTT 계약이 시뮬 좌표
--   fork_height                     시뮬 단위 (13.25)          ← 그대로 task.dropoff 로 나감
--   usable_height                   실물 미터 (m)              ← 화물 높이와 비교하므로
--
-- 근거:
--   · F팀 문서 — "MQTT 위의 모든 좌표는 시뮬레이션 좌표계(20 × 30)", "백엔드는 아무 변환도
--     하지 않는다". destination_x/y 와 fork_height 는 task 페이로드로 그대로 나간다.
--   · PlacementService — usable_height 를 `cargoHeight + palletHeight(0.12m) + clearance(0.25m)`
--     와 비교한다. cargoHeight 는 카메라 측정값(실물 m)이라 usable_height 도 m 여야 한다.
--   · 같은 문서 — cargo 페이로드의 `height` 만 실물 m 이라고 명시.
--
-- 즉 fork_height 13.25 는 "13.25 m"가 아니라 시뮬 단위다(실물 약 1.325 m).
-- 이 혼재는 이 파일이 만든 것이 아니라 기존 계약이 그렇다. 통일하려면 F팀·C팀 합의가
-- 먼저이고, 그 전에 한쪽만 바꾸면 차량이 엉뚱한 곳으로 간다.
--
-- =============================================================================
-- 🔴 2. usable_height 는 F팀 문서에 없다 — 아래 값은 자리표시자다
-- =============================================================================
-- 문서가 준 것은 좌표와 포크 목표 높이뿐이고, "한 칸에 얼마나 높은 화물이 들어가는가"는
-- 없다. 그런데 컬럼이 NOT NULL 이고 CHECK(usable_height > 0) 이라 비워 둘 수 없다.
--
-- 그래서 **1.00 m 를 넣었다. 이 값은 측정된 것이 아니다.**
-- 실측 전까지는 "높이가 1m 를 넘는 화물은 어느 칸에도 안 들어간다"로 동작한다.
--
-- ⚠️ 실측 후 반드시 갱신할 것:
--     UPDATE storage_slot SET usable_height = <실측 m> WHERE slot_code = 'A1';
--
-- usable_width 는 NULL 로 둔다 — NULL 은 "폭 제약을 모른다"는 뜻이고 폭 검사를 건너뛴다.
-- 0 으로 채우면 모든 화물이 탈락하므로 절대 쓰지 말 것(PlacementService 주석 참고).
--
-- =============================================================================
-- 3. destination_x 에 "접근점"을 넣는 이유
-- =============================================================================
-- F팀 문서: "접근점까지만 Nav2 로 가고, 그 뒤 도킹·적재·후진은 차량이 자체 수행한다.
--            백엔드는 접근점 도착을 확인한 뒤 place_rack 만 보내면 된다."
-- 따라서 도킹 x(2.60/11.95)·적재점 x(0.95/10.20)는 차량 몫이라 DB 에 넣지 않는다.
-- 넣어 두면 백엔드가 그리로 보내야 하는 것처럼 오해를 부른다.
--
-- destination_heading 은 degree 다(스키마 주석 기준). 문서의 yaw 3.1416 rad = 180.0 도.
-- =============================================================================

