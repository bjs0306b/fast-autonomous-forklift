-- =============================================================================
-- 랙 0층(바닥) 슬롯 추가 + 1층 유효 높이 실측 반영 (2026-08-10)
-- =============================================================================
--
-- 실행: mysql ... < seed-rack-slots-level0.sql
--       `seed-rack-slots.sql` 을 먼저 적용한 DB 에서 돌린다.
--
-- =============================================================================
-- 1. 기존 24 칸은 **1층(선반)** 이다
-- =============================================================================
--
-- 처음에는 기존 칸을 0층으로 잡았는데 거꾸로였다. 근거는 F팀 정본 파일이다.
--
--     rack_slots.csv:  A1,5.0,9.3,2.6,9.3,0.95,9.3,1.325,...
--                                                   ^^^^^ place_z
--
-- 적재 지점 z 가 1.325 다. 그것이 선반 윗면이고 "0층 / 1층 경계" 다. 즉 지금까지
-- 백엔드도 시뮬도 **선반 한 층만** 알고 있었다. DB 의 fork_height 1.325 도 같은 값이다.
--
-- 그래서 기존 A001..A012 · B001..B012 는 그대로 두고(1층), **바닥을 새로 추가**한다.
--
-- =============================================================================
-- 2. slot_code — 왜 AF01 인가
-- =============================================================================
--
--     1층(선반)  A001..A012 · B001..B012   ← 기존. 건드리지 않는다
--     0층(바닥)  AF01..AF12 · BF01..BF12   ← 신규. F = Floor
--
-- 기존 이름을 못 바꾼다. slot_code 는 PK 이고 transport_task.destination_slot_code 가
-- FK 로 참조한다(schema.sql:180) — 바꾸면 진행 중인 운반 작업이 끊긴다.
--
-- `A0xx` 로 층을 표현하려 했으나 기존 `A001` 과 형태가 겹쳐 구분이 안 된다. 글자를 하나
-- 넣어 눈으로도 갈리게 했다.
--
-- =============================================================================
-- 3. 층별 높이 — 어디서 온 값인가
-- =============================================================================
--
-- F팀 실측(2026-08-10):
--     0층 칸 높이 = 1.325 (시뮬) = 0.1325 실물   ← 바닥 ~ 1층 선반. 실측 0.14
--     1층 칸 높이 = 2.0   (시뮬) = 0.2    실물   ← 1층 선반 ~ 2층 선반
--   두 값은 **칸의 높이**지 경계 위치가 아니다. 처음에 경계로 읽고 2.0-1.325 를 1층
--
--   높이로 잡았다가 1층이 0.0675 가 되어 3cm 짜리만 들어가는 이상한 랙이 됐다.
--
-- ⚠️ **랙 A 와 B 는 선반 높이가 다르다**(2026-08-10, 실물 확인). 처음에는 둘이 같은 줄
--    알고 한 값으로 넣었는데, B 는 선반이 더 낮게 달려 있어 0층이 좁고 1층이 넓다.
--
--   랙   층   칸 높이(시뮬)   usable_height(실물 m)   fork_height(시뮬)
--   A    0층  1.35            0.14  ← 실측             0.0
--   A    1층  2.0             0.2                     1.325
--   B    0층  1.0             0.1                     0.0
--   B    1층  2.35            0.235                   1.0   ← 선반이 낮으니 포크도 낮다
--
--    F팀 정본 `rack_slots.csv` 는 A1·B1 둘 다 `place_z 1.325` 로 **같다.** 시뮬은
--    자기완결적이라 이 차이가 안 보이고, 어긋나는 것은 실물 포크뿐이다. 시뮬에 B 랙
--    선반을 내리려면 그쪽 CSV 도 함께 고쳐야 한다(계약 문서 §6 로 전달할 것).
--
-- ⚠️ **단위가 컬럼마다 다르다**(seed-rack-slots.sql §1 참고).
--    `fork_height` · `destination_*` 는 **시뮬 단위**(실물 ×10)로 그대로 task 에 나가고,
--    `usable_height` 는 **실물 m** 라 카메라가 잰 화물 높이와 같은 자에서 비교된다.
--    그래서 1층은 시뮬 2.0 을 ÷10 해서 넣는다. 값을 바꿀 때 주의할 것.
--
-- ⚠️ 0층 0.14 는 "선반 **아랫면**까지" 로 받은 값이다. 그것이 선반 **윗면** 높이였다면
--    0층 유효 높이는 `0.14 - 선반두께` 이고 fork_height 도 1.325 → 1.40 이어야 한다.
--    orin-rack-spec.md §10 이 이 값을 "확인이 필요한 값" 으로 분류해 두었다.
--
-- 2층은 만들지 않는다 — 있기는 하나 지게차가 물리적으로 닿지 못해 팀이 제외했다.
--
-- =============================================================================
-- 4. 이 값으로 들어가는 화물 높이
-- =============================================================================
--
--     required = 화물높이 + 팔레트 0.012 + 여유 0.025      (모형 스케일)
--
--     A 0층  0.14  ≥ required  →  화물 ≤ 0.103 m (10.3 cm)
--     A 1층  0.2   ≥ required  →  화물 ≤ 0.163 m (16.3 cm)
--     B 0층  0.1   ≥ required  →  화물 ≤ 0.063 m ( 6.3 cm)
--     B 1층  0.235 ≥ required  →  화물 ≤ 0.198 m (19.8 cm)
--
-- 즉 화물이 커질수록 0층에서 밀려 1층으로 올라가고, A 1층에도 안 들어가는 큰 화물은
-- B 1층으로 간다. 주기 설정의 무작위 상한(0.19)이 B 1층 한계 안에 있는 이유다.
--
-- =============================================================================

-- 1층 — 실측 반영. 기존 2.00 은 F팀 문서에 값이 없어 팀이 임의로 정했던 자리표시자였다
-- (seed-rack-slots.sql §2). 그 값으로는 어떤 화물도 걸러지지 않았다.
UPDATE storage_slot
   SET usable_height = 0.2
 WHERE slot_code REGEXP '^A[0-9]{3}$';

-- 랙 B 1층 — 선반이 A 보다 낮게 달려 있다. 칸이 그만큼 넓고(2.35) 포크는 낮게(1.0) 든다.
--
-- ⚠️ **UPDATE 로 둔다.** 아래 0층은 `INSERT IGNORE` 라 이미 있는 행을 안 고치는데, 이
--    값들은 seed 를 한 번 돌린 뒤에 바뀐 것이라 INSERT 만으로는 영영 반영되지 않는다.
--    UPDATE 는 몇 번 돌려도 같은 결과다.
UPDATE storage_slot
   SET usable_height = 0.235,
       fork_height   = 1.0
 WHERE slot_code REGEXP '^B[0-9]{3}$';

-- 랙 B 0층 — 위와 같은 이유로 UPDATE 를 함께 둔다(신규 DB 는 아래 INSERT 가 넣는다).
UPDATE storage_slot
   SET usable_height = 0.1
 WHERE slot_code REGEXP '^BF[0-9]{2}$';

