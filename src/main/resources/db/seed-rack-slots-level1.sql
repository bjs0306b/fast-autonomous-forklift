-- =============================================================================
-- 랙 1층 슬롯 추가 + 0층 유효 높이 실측 반영 (2026-08-10)
-- =============================================================================
--
-- `seed-rack-slots.sql` 이 만든 24 칸은 전부 **0층**이다. 여기에 1층 24 칸을 더해
-- 48 칸으로 만들고, 0층의 `usable_height` 를 실측값으로 고친다.
--
-- 실행: mysql ... < seed-rack-slots-level1.sql
--       `seed-rack-slots.sql` 을 먼저 적용한 DB 에서 돌린다.
--
-- =============================================================================
-- 1. slot_code 규칙 — <랙><층><칸2자리>
-- =============================================================================
--
--     A001  →  랙 A · 0층 · 1칸
--     A101  →  랙 A · 1층 · 1칸
--
-- **기존 24 칸을 그대로 둔다.** `slot_code` 는 PK 이고 `transport_task
-- .destination_slot_code` 가 FK 로 참조한다(schema.sql:180). 이름을 바꾸면 진행 중인
-- 운반 작업이 끊긴다. 다행히 기존 `A001` 이 위 규칙에 이미 들어맞는다 — 규칙을 새로
-- 만든 게 아니라, 원래 그렇게 읽히는 이름이었다고 보면 된다.
--
-- =============================================================================
-- 2. 층별 높이 — 어디서 온 값인가
-- =============================================================================
--
-- F팀 실측(2026-08-10):
--     0층 / 1층 경계  = 1.325 (시뮬)   ← 1층 선반 윗면. fork_height 와 _SHELF_Z 가 같은 값
--     1층 / 2층 경계  = 2.0   (시뮬)
--     0층 칸 높이      = 0.14 m (실물 모형 실측)
--
--   층   구간(시뮬)      usable_height(실물 m)   fork_height(시뮬)
--   ---  -------------  ---------------------  -----------------
--   0층  0     ~ 1.325   0.14   ← 실측          0.0
--   1층  1.325 ~ 2.0     0.0675 = (2.0-1.325)/10 1.325
--
-- ⚠️ **단위가 컬럼마다 다르다**(seed-rack-slots.sql §1 참고).
--    `fork_height` · `destination_*` 는 **시뮬 단위**(실물 ×10)로 그대로 task 에 나가고,
--    `usable_height` 는 **실물 m** 라 카메라가 잰 화물 높이와 같은 자에서 비교된다.
--    그래서 1층은 시뮬 0.675 를 ÷10 해서 넣는다. 헷갈리기 쉬우니 값을 바꿀 때 주의할 것.
--
-- ⚠️ 0층 0.14 는 "선반 **아랫면**까지" 로 받은 값이다. 만약 그것이 선반 **윗면** 높이였다면
--    0층 유효 높이는 `0.14 - 선반두께` 이고 fork_height 도 1.325 → 1.40 이어야 한다.
--    후자라면 실물 지게차가 7.5 mm 낮게 포크를 올린다(시뮬은 자기완결적이라 티가 안 난다).
--
-- 2층은 만들지 않는다 — 있기는 하나 지게차가 물리적으로 닿지 못해 팀이 제외했다.
--
-- =============================================================================
-- 3. 이 값으로 들어가는 화물 높이
-- =============================================================================
--
--     required = 화물높이 + 팔레트 0.012 + 여유 0.025      (모형 스케일)
--
--     0층  0.14   ≥ required  →  화물 ≤ 0.103  m (10.3 cm)
--     1층  0.0675 ≥ required  →  화물 ≤ 0.0305 m ( 3.0 cm)
--
-- 1층이 3 cm 짜리만 받는다. 실제 화물이 그보다 크면 0층만 쓰이고, 0층이 다 찬 뒤에야
-- 1층이 의미를 갖는다. "낮은 층 먼저" 정책(PlacementService)과도 어긋나지 않는다.
--
-- =============================================================================

-- 0층 — 실측 반영. 기존 2.00 은 F팀 문서에 값이 없어 팀이 임의로 정했던 자리표시자였다
-- (seed-rack-slots.sql §2). 그 값으로는 어떤 화물도 걸러지지 않았다.
UPDATE storage_slot
   SET usable_height = 0.14
 WHERE slot_code REGEXP '^[AB]0[0-9]{2}$';

